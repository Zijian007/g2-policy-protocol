"""Generate constants and straight-line static checks from g2.schema.json.

Only the small keyword subset used for native scalar/object/array fields is
compiled. NumPy/image representation and cross-field semantics stay in Python.
An unsupported keyword fails generation rather than silently dropping a rule.
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1] / 'src/g2_policy_protocol'
# These decoded values need NumPy/image checks, not nested JSON element loops.
_NATIVE_VALUES = {'pose', 'joint', 'actions', 'image'}


def render(schema=None):
    if schema is None:
        schema = json.loads((ROOT / 'g2.schema.json').read_text())
    defs, layout = schema['$defs'], schema['x-g2']
    metadata = defs['metadata']['properties']
    values = {
        'PROTOCOL': metadata['protocol']['const'],
        **{key.upper(): tuple(value) if isinstance(value, list) else value for key, value in layout.items()},
    }
    for name in ('pose', 'joint'):
        node = defs[f'{name}_values']
        dim = node['minItems']
        if node['maxItems'] != dim or len(layout[f'{name}_fields']) != dim:
            raise ValueError(f'{name} dimensions disagree with layout')
        if defs[name]['anyOf'][1]['properties']['shape']['const'] != [dim]:
            raise ValueError(f'{name} encoded shape disagrees with layout')
        values[f'{name.upper()}_DIM'] = dim
    action = defs['actions']['anyOf'][1]['properties']
    if action['shape']['prefixItems'][1].get('const', values['POSE_DIM']) != values['POSE_DIM']:
        raise ValueError('actions width disagrees with pose')
    values['ACTION_NDIM'] = action['shape']['minItems']
    values['ACTION_MIN_ROWS'] = defs['actions']['anyOf'][0]['minItems']
    if action['data']['minItems'] != values['ACTION_MIN_ROWS'] or action['shape']['prefixItems'][0]['minimum'] != values['ACTION_MIN_ROWS']:
        raise ValueError('actions length constraints disagree')
    image = defs['image']['anyOf'][1]['properties']
    values['IMAGE_DTYPE'] = image['dtype']['const']
    values['IMAGE_NDIM'] = image['shape']['minItems']
    values['IMAGE_CHANNELS'] = image['shape']['prefixItems'][-1]['const']
    values['IMAGE_MIN_HW'] = tuple(item['minimum'] for item in image['shape']['prefixItems'][:-1])
    pixel = image['data']['items']['items']
    if (values['IMAGE_NDIM'] != len(image['shape']['prefixItems'])
            or len(values['IMAGE_MIN_HW']) != 2
            or pixel['minItems'] != values['IMAGE_CHANNELS']
            or pixel['maxItems'] != values['IMAGE_CHANNELS']):
        raise ValueError('image shape constraints disagree')
    for name in (name for name in ('metadata', 'obs', 'action', 'error', 'reset', 'reset_ack') if name in defs):
        values[f'{name.upper()}_TYPE'] = defs[name]['properties']['type']['const']
        values[f'{name.upper()}_FIELDS'] = tuple(defs[name]['properties'])
        values[f'{name.upper()}_REQUIRED'] = tuple(defs[name]['required'])
    for key in ('arm', 'image_encoding', 'image_resize'):
        values[f'{key.upper()}_VALUES'] = tuple(metadata[key]['enum'])
    lines = [
        '# Generated by tools/generate_protocol.py. Do not edit.',
        'from ._validation import (',
        '    array as _array,',
        '    integer as _integer,',
        '    number as _number,',
        '    object_fields as _object_fields,',
        '    text as _text,',
        ')',
        '',
        *[f'{key} = {value!r}' for key, value in values.items()],
    ]

    def emit(node, value, label, indent, skip_fields=()):
        def line(code):
            lines.append('    ' * indent + code)
        if '$ref' in node:
            if node.keys() - {'$ref', 'description', '$comment'}:
                raise ValueError(f'unsupported reference siblings: {node}')
            name = node['$ref'].removeprefix('#/$defs/')
            if name in _NATIVE_VALUES:
                return
            emit(defs[name], value, label, indent)
            return
        if 'anyOf' in node:
            # RTC prefix: the non-null alternative is checked by the NumPy path.
            if node == {'anyOf': [{'$ref': '#/$defs/actions'}, {'type': 'null'}]}:
                return
            raise ValueError(f'unsupported static union: {node}')
        common = {'description', '$comment'}
        allowed = {
            'integer': {'type', 'minimum'},
            'number': {'type', 'minimum', 'exclusiveMinimum'},
            'string': {'type', 'minLength'},
            'boolean': {'type'},
            'object': {'type', 'properties', 'required', 'additionalProperties'},
            'array': {'type', 'items', 'minItems', 'maxItems', 'uniqueItems'},
        }.get(node.get('type'), {'const', 'enum'}) | common
        if node.keys() - allowed:
            raise ValueError(f'unsupported static keywords: {node.keys() - allowed}')
        if 'const' in node or 'enum' in node:
            condition = f"{value} != {node['const']!r}" if 'const' in node else f"{value} not in {tuple(node['enum'])!r}"
            line(f'if {condition}:')
            line(f'    raise ValueError({label!r} + " has an unsupported value")')
            return
        kind = node['type']
        if kind == 'integer':
            line(f'_integer({value}, {label!r}, minimum={node["minimum"]!r})')
        elif kind == 'number':
            args = ''.join(f', {key}={node[source]!r}' for source, key in
                           (('minimum', 'minimum'), ('exclusiveMinimum', 'exclusive_minimum')) if source in node)
            line(f'_number({value}, {label!r}{args})')
        elif kind == 'string':
            line(f'_text({value}, {label!r}, min_length={node.get("minLength", 0)!r})')
        elif kind == 'boolean':
            line(f'if not isinstance({value}, bool):')
            line(f'    raise ValueError({label!r} + " must be boolean")')
        elif kind == 'object':
            props = node.get('properties', {})
            fields = tuple(props) if node.get('additionalProperties') is False else None
            line(f'_object_fields({value}, {label!r}, fields={fields!r}, required={tuple(node.get("required", ()))!r})')
            for key, child in props.items():
                if key in skip_fields:
                    continue
                optional = key not in node.get('required', ())
                if optional:
                    line(f'if {key!r} in {value}:')
                emit(child, f'{value}[{key!r}]', f'{label}.{key}', indent + optional)
                # A skipped NumPy field has no emitted body.
                if optional and lines[-1].strip() == f'if {key!r} in {value}:':
                    lines.pop()
            if isinstance(node.get('additionalProperties'), dict):
                line(f'for item{indent} in {value}.values():')
                emit(node['additionalProperties'], f'item{indent}', label, indent + 1)
        elif kind == 'array':
            line(f'_array({value}, {label!r}, minimum={node.get("minItems")!r}, maximum={node.get("maxItems")!r}, unique={node.get("uniqueItems", False)!r})')
            line(f'for item{indent} in {value}:')
            emit(node['items'], f'item{indent}', label, indent + 1)
        else:
            raise ValueError(f'unsupported static type: {kind}')

    for name in (name for name in ('metadata', 'obs', 'action', 'error', 'reset', 'reset_ack') if name in defs):
        lines.extend(['', '', f'def validate_{name}_fields(payload):'])
        emit(defs[name], 'payload', name, 1, skip_fields={'images'} if name == 'obs' else ())
    # Images are checked once by protocol.validate_images, also used after JPEG decode.
    lines.extend(['', '', 'def validate_images_fields(payload):'])
    emit(defs['obs']['properties']['images'], 'payload', 'images', 1)
    # Shared scalar checks also validate caller-side expectations before comparisons.
    for name, node in (('request_id', defs['request_id']), ('policy_hz', metadata['policy_hz'])):
        lines.extend(['', '', f'def validate_{name}(value):'])
        emit(node, 'value', name, 1)
    return '\n'.join(lines) + '\n'


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    path = ROOT / '_generated.py'
    expected = render()
    if args.check:
        if not path.is_file() or path.read_text() != expected:
            raise SystemExit('Generated contract is stale; run tools/generate_protocol.py')
    else:
        path.write_text(expected)
